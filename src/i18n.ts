export function t(
  lang: Language,
  key: keyof typeof translations["zh-CN"],
  params?: Record<string, string | number>
): string {
  const dict = translations[lang] || translations["zh-CN"];
  let str = dict[key] || translations["zh-CN"][key] || (key as string);
  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${pKey}\\}`, "g"), String(pVal));
    }
  }
  return str;
}

export function formatResetTimeI18n(value: string, lang: Language): string {
  const resetMs = Date.parse(value);
  if (Number.isNaN(resetMs)) return value || t(lang, "resetNotProvided");

  const diffMs = resetMs - Date.now();
  if (diffMs <= 0) {
    return t(lang, "resetingSoon");
  }

  const diffSeconds = Math.floor(diffMs / 1000);
  const days = Math.floor(diffSeconds / 86400);
  const hours = Math.floor((diffSeconds % 86400) / 3600);
  const minutes = Math.floor((diffSeconds % 3600) / 60);

  if (days > 0) {
    if (hours > 0) {
      return t(lang, "resetDaysHours", { days, hours });
    }
    return t(lang, "resetDays", { days });
  }

  if (hours > 0) {
    if (minutes > 0) {
      return t(lang, "resetHoursMinutes", { hours, minutes });
    }
    return t(lang, "resetHours", { hours });
  }

  if (minutes > 0) {
    return t(lang, "resetMinutes", { minutes });
  }

  return t(lang, "resetLessThanMinute");
}

export function formatTimeI18n(seconds: number, lang: Language): string {
  const locale = lang === "zh-TW" ? "zh-TW" : lang === "en-US" ? "en-US" : "zh-CN";
  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(seconds * 1000));
}
